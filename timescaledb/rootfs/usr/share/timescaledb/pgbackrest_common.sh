#!/command/with-contenv bashio
# shellcheck shell=bash
# ==============================================================================
# Home Assistant Add-on: TimescaleDb
# Shared functions of the optional pgBackRest integration (the pgbackrest option).
# Sourced by the init, backup and service scripts. Nothing here does anything
# unless pgbackrest.enabled is true: callers check pgbr_enabled first.
# ==============================================================================

# shellcheck disable=SC2034
PGBR_RUN=/run/pgbackrest
PGBR_CONF="${PGBR_RUN}/pgbackrest.conf"
PGBR_INCLUDE="${PGBR_RUN}/conf.d"
PGBR_SECRETS="${PGBR_INCLUDE}/secrets.conf"
PGBR_STATE=/data/pgbackrest
PGBR_POINTER="${PGBR_STATE}/pointer.json"
PGBR_CREDENTIALS=/config/pgbackrest/credentials.conf
PGBR_POSTGRES_DATA=/data/postgres

pgbr_enabled() {
    bashio::config.true 'pgbackrest.enabled'
}

# Option $1 (below pgbackrest.), or the default $2 when it is not set
pgbr_opt() {
    if bashio::config.has_value "pgbackrest.${1}"; then
        bashio::config "pgbackrest.${1}"
    else
        printf '%s' "${2:-}"
    fi
}

pgbr_stanza() {
    pgbr_opt stanza timescaledb
}

pgbr_repo_type() {
    pgbr_opt repo_type s3
}

pgbr_repo_path() {
    if [[ "$(pgbr_repo_type)" == "posix" ]]; then
        pgbr_opt repo_path /share/timescaledb/pgbackrest
    else
        pgbr_opt repo_path /timescaledb/pgbackrest
    fi
}

# Runs pgBackRest for the stanza as the postgres user
pgbr_run() {
    s6-setuidgid postgres pgbackrest \
        "--config=${PGBR_CONF}" "--config-include-path=${PGBR_INCLUDE}" \
        "--stanza=$(pgbr_stanza)" "$@"
}

# Fails when a value cannot go in a pgBackRest ini file: a newline would add a line.
# $1: name, $2: value
pgbr_check_value() {
    if [[ "${2}" == *$'\n'* ]]; then
        bashio::exit.nok "pgbackrest: the value of ${1} contains a line break"
    fi
}

# Writes the files of /run/pgbackrest on every start, so removing an option removes it
# from the configuration. Secrets go in their own file (see pgbr_render_secrets).
pgbr_render_config() {
    local type
    local retention
    local queue_max
    type="$(pgbr_repo_type)"
    if [[ "${type}" == "s3" ]] && { ! bashio::config.has_value 'pgbackrest.s3_endpoint' || ! bashio::config.has_value 'pgbackrest.s3_bucket'; }; then
        bashio::exit.nok "pgbackrest: repo_type s3 needs s3_endpoint and s3_bucket"
    fi
    retention="$(pgbr_opt retention_full 4)"
    queue_max="$(pgbr_opt archive_queue_max 2GiB)"

    mkdir -p "${PGBR_INCLUDE}" "${PGBR_STATE}/spool" "${PGBR_STATE}/log"
    chown root:postgres "${PGBR_RUN}" "${PGBR_INCLUDE}"
    chmod 750 "${PGBR_RUN}" "${PGBR_INCLUDE}"
    chown -R postgres:postgres "${PGBR_STATE}"
    chmod 700 "${PGBR_STATE}"

    if [[ "${type}" == "posix" ]]; then
        # /share and /media are root-owned, and pgBackRest runs as postgres: give it its own directory
        mkdir -p "$(pgbr_repo_path)"
        chown postgres:postgres "$(pgbr_repo_path)" \
            || bashio::log.warning "Could not make $(pgbr_repo_path) writable for postgres: the repository may be on storage that does not allow it."
    fi

    {
        echo "# Generated by the TimescaleDB add-on from the pgbackrest option. Rewritten on every start."
        echo "[global]"
        echo "repo1-type=${type}"
        echo "repo1-path=$(pgbr_repo_path)"
        if [[ "${type}" == "s3" ]]; then
            echo "repo1-s3-endpoint=$(pgbr_opt s3_endpoint)"
            echo "repo1-s3-bucket=$(pgbr_opt s3_bucket)"
            echo "repo1-s3-region=$(pgbr_opt s3_region us-east-1)"
            echo "repo1-s3-uri-style=$(pgbr_opt s3_uri_style host)"
            if bashio::config.false 'pgbackrest.s3_verify_tls'; then
                echo "repo1-storage-verify-tls=n"
            fi
        fi
        echo "repo1-retention-full=${retention}"
        if ! bashio::config.false 'pgbackrest.block_incremental'; then
            # Block incremental backups: diff and incr copy only the changed blocks of a file
            echo "repo1-bundle=y"
            echo "repo1-block=y"
        fi
        echo "compress-type=zst"
        echo "archive-async=y"
        echo "spool-path=${PGBR_STATE}/spool"
        # Past this size of unarchived WAL, WAL is dropped instead of filling /data
        echo "archive-push-queue-max=${queue_max}"
        echo "process-max=2"
        echo "log-level-console=info"
        echo "log-level-file=warn"
        echo "log-path=${PGBR_STATE}/log"
        echo "start-fast=y"
        echo
        echo "[$(pgbr_stanza)]"
        echo "pg1-path=${PGBR_POSTGRES_DATA}"
        echo "pg1-socket-path=/run/postgresql"
    } > "${PGBR_CONF}"
    chown root:postgres "${PGBR_CONF}"
    chmod 640 "${PGBR_CONF}"

    pgbr_render_secrets
}

# The credentials come from the options, or else from /config/pgbackrest/credentials.conf
# (on the host: /addon_configs/<slug>/pgbackrest/credentials.conf), which is left out of
# Home Assistant backups. The options win when both are set.
# Writes /run/pgbackrest/conf.d/secrets.conf, readable by postgres: archive_command runs as it.
pgbr_render_secrets() {
    local key secret cipher from_file=""
    # Straight from the options file (0600), never through a command's arguments
    key="$(jq -r '.pgbackrest.s3_key // empty' /data/options.json)"
    secret="$(jq -r '.pgbackrest.s3_key_secret // empty' /data/options.json)"
    cipher="$(jq -r '.pgbackrest.cipher_pass // empty' /data/options.json)"

    if [[ -f "${PGBR_CREDENTIALS}" ]]; then
        if [[ -n "${key}${secret}${cipher}" ]]; then
            bashio::log.warning "pgbackrest: the options and ${PGBR_CREDENTIALS} both hold credentials, using the options."
        else
            from_file="$(grep -E '^(repo1-s3-key|repo1-s3-key-secret|repo1-cipher-pass)=' "${PGBR_CREDENTIALS}" || true)"
        fi
    fi

    pgbr_check_value s3_key "${key}"
    pgbr_check_value s3_key_secret "${secret}"
    pgbr_check_value cipher_pass "${cipher}"

    (
        umask 077
        {
            echo "[global]"
            [[ -z "${key}" ]] || echo "repo1-s3-key=${key}"
            [[ -z "${secret}" ]] || echo "repo1-s3-key-secret=${secret}"
            [[ -z "${cipher}" ]] || echo "repo1-cipher-pass=${cipher}"
            [[ -z "${from_file}" ]] || echo "${from_file}"
            if [[ -n "${cipher}" ]] || [[ "${from_file}" == *repo1-cipher-pass=* ]]; then
                echo "repo1-cipher-type=aes-256-cbc"
            fi
        } > "${PGBR_SECRETS}.new"
    )
    chown postgres:postgres "${PGBR_SECRETS}.new"
    chmod 600 "${PGBR_SECRETS}.new"
    mv "${PGBR_SECRETS}.new" "${PGBR_SECRETS}"
}

# Returns success when the repository can be reached with what is configured:
# for S3 that means a key and secret
pgbr_credentials_ok() {
    [[ "$(pgbr_repo_type)" == "posix" ]] && return 0
    grep -q '^repo1-s3-key=' "${PGBR_SECRETS}" && grep -q '^repo1-s3-key-secret=' "${PGBR_SECRETS}"
}

# Sets an option below pgbackrest. to a JSON value, in the options of the add-on.
# $1: option, $2: JSON value
pgbr_set_option() {
    if [[ -n "${SUPERVISOR_TOKEN:-}" ]]; then
        # The options may hold secrets: in a file, not in a command's arguments
        (
            umask 077
            body="$(mktemp /dev/shm/pgbr.XXXXXX)"
            trap 'rm -f "${body}"' EXIT
            bashio::addon.options | jq -c --argjson v "${2}" ".pgbackrest.${1} = \$v | {options: .}" > "${body}"
            printf 'Authorization: Bearer %s\n' "${SUPERVISOR_TOKEN}" | curl -sSf -X POST -H @- -H 'Content-Type: application/json' \
                --data-binary "@${body}" http://supervisor/addons/self/options > /dev/null
        )
    elif [[ -f /data/options.json ]]; then
        # Standalone: there is no Supervisor, the options file is all there is
        jq -c --argjson v "${2}" ".pgbackrest.${1} = \$v" /data/options.json > /data/options.json.new
        mv /data/options.json.new /data/options.json
    fi
}

pgbr_pg_major() {
    cat "${PGBR_POSTGRES_DATA}/PG_VERSION"
}

pgbr_system_id() {
    "/usr/libexec/postgresql$(pgbr_pg_major)/pg_controldata" "${PGBR_POSTGRES_DATA}" \
        | sed -n 's/^Database system identifier: *//p'
}
